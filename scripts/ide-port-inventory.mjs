#!/usr/bin/env node
// What porting ACRYL's IDE means, package by package, from the ACRYL checkout (read only): each package's size, its tests, its exact dependencies split into run-time, peer and workspace,
// the DSH client packages its bundle needs, and what has to change for it to live beside the framework (one copy of `acrylblends`, no workspace links).
//   node scripts/ide-port-inventory.mjs <ACRYL checkout> > docs/plans/ide-port-packages.md
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs'
import { join } from 'node:path'

const checkout = process.argv[2]
if (!checkout) throw new Error('usage: node scripts/ide-port-inventory.mjs <ACRYL checkout>')

/** The packages of the port, in slice order, and why. `port` is ported with its tests; `replace` is what the framework already has; `reference` is read, not ported. */
const WANTED = [
  [
    'acryl-app-shell',
    'port',
    1,
    'the frame: three columns, collapsible and resizable panels, layout state, theme, title-bar spacing',
  ],
  ['@acryl/ui', 'port', 1, 'the design: themed components, semantic colour roles, slot helpers'],
  [
    'acryl-settings',
    'port',
    1,
    'the preferences service (one YAML file) the frame and the workspace read',
  ],
  [
    'acryl-brand',
    'port',
    1,
    'configurable name, mark, accent, font and page title (config only, no source)',
  ],
  [
    'dsh-client-ui-brand-acryl',
    'port',
    1,
    "the ACRYL brand in DSH's sidebar and conversation hero (ported in slice 0)",
  ],
  ['acryl-shortcuts', 'port', 1, 'the keyboard commands and Settings > Shortcuts'],
  ['acryl-plugin-admin', 'port', 1, 'Settings > Plugins: lifecycle and architecture tabs'],
  ['acryl-support', 'port', 1, 'Settings > Support: logs and the diagnostics archive'],
  [
    'acryl-workspace',
    'port',
    2,
    'the workspace: projects, tabs per worktree, terminals, git, files, diff, review, checks, board, docs',
  ],
  [
    'acryl-sign-in',
    'port',
    5,
    'account sign-in (OAuth) for Claude, ChatGPT/Codex and DeepSeek from Settings > Models',
  ],
  [
    'acryl-control',
    'port',
    1,
    'guarded agent control core and the `acrylWeb` port the others inject',
  ],
  [
    'acryl-diagnostics',
    'port',
    1,
    'the diagnostics archive `acryl-support` writes (system facts, masked logs)',
  ],
  [
    'acryl-agent-control',
    'reference',
    1,
    "ACRYL's own door; this repository's `acryl-door` is adapted instead",
  ],
  [
    'acryl-loopback-http',
    'replace',
    1,
    'loopback and origin guard; `acrylblends/loopback-only` covers it',
  ],
  ['acryl-mount-anchors', 'reference', 0, 'visual mount-anchor inspector; not part of the frame'],
  ['acryl-app-save', 'reference', 0, 'save to git from the app; the framework has `save`'],
]

const roots = ['plugins', 'runtime']
const folders = new Map()
for (const root of roots)
  for (const name of readdirSync(join(checkout, root))) {
    const file = join(checkout, root, name, 'package.json')
    if (existsSync(file))
      folders.set(JSON.parse(readFileSync(file, 'utf8')).name, join(checkout, root, name))
  }

const walk = (dir, match) =>
  !existsSync(dir)
    ? []
    : readdirSync(dir).flatMap((entry) => {
        if (entry === 'node_modules' || entry === 'lib') return []
        const path = join(dir, entry)
        return statSync(path).isDirectory() ? walk(path, match) : match(path) ? [path] : []
      })
const lines = (files) =>
  files.reduce((n, file) => n + readFileSync(file, 'utf8').split('\n').length, 0)
const source = /\.(ts|tsx)$/u
const isTest = (path) => /\.(test|spec)\.(ts|tsx)$/u.test(path) || /[\\/]tests?[\\/]/u.test(path)
const list = (record) => Object.entries(record ?? {}).map(([name, range]) => `\`${name}\` ${range}`)

const out = []
const say = (line = '') => out.push(line)
say("# The packages of the IDE port, from ACRYL's checkout")
say()
say(
  `Generated by \`scripts/ide-port-inventory.mjs\` from a checkout of \`acryldev/acryl\` (\`main\`, 9073312d). Read only: nothing in that repository was changed. Counts exclude \`node_modules\`, built \`lib\` and tests; "tests" are spec and test files.`,
)
say()
say('| Slice | Package | Action | Version | Source files / lines | Tests | Why |')
say('| --- | --- | --- | --- | --- | --- | --- |')
const details = []
for (const [name, action, slice, why] of WANTED) {
  const dir = folders.get(name)
  if (dir === undefined) {
    say(`| ${slice} | \`${name}\` | ${action} | not found | | | ${why} |`)
    continue
  }
  const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  const all = walk(join(dir), (path) => source.test(path) && !path.endsWith('.d.ts'))
  const tests = all.filter(isTest)
  const code = all.filter((path) => !isTest(path))
  say(
    `| ${slice} | \`${name}\` | ${action} | ${manifest.version} | ${code.length} / ${lines(code)} | ${tests.length} | ${why} |`,
  )
  details.push([name, action, manifest, dir, code, tests])
}
say()
say('## Dependencies, exactly')
say()
say(
  "For each package: what its `package.json` asks for. **Workspace** names are other ACRYL packages (listed above or not; a workspace dependency outside this table is something the port has to bring or replace). **Framework** is the one line that must change: ACRYL packages declare `acrylblends` ^0.9.2 as a dependency, which installs a second router beside the app's; a ported package declares it as a peer. **DSH client** is what its `client.js` bundle calls through the page's module table (`dsh.client.inject`).",
)
say()
for (const [name, action, manifest, , code, tests] of details) {
  const workspace = Object.entries({
    ...manifest.dependencies,
    ...manifest.peerDependencies,
    ...manifest.devDependencies,
  })
    .filter(([, range]) => String(range).startsWith('workspace:'))
    .map(([n]) => n)
  const runtime = list(
    Object.fromEntries(
      Object.entries(manifest.dependencies ?? {}).filter(
        ([, r]) => !String(r).startsWith('workspace:'),
      ),
    ),
  )
  const peers = list(
    Object.fromEntries(
      Object.entries(manifest.peerDependencies ?? {}).filter(
        ([, r]) => !String(r).startsWith('workspace:'),
      ),
    ),
  )
  const framework = manifest.dependencies?.acrylblends ?? manifest.peerDependencies?.acrylblends
  const client = manifest.dsh?.client
  const dshImports = [
    ...new Set(
      code.flatMap((file) =>
        [...readFileSync(file, 'utf8').matchAll(/from '(@deepseek-ai\/dsh-[a-z-]+)/gu)].map(
          (m) => m[1],
        ),
      ),
    ),
  ].sort()
  say(`### ${name} (${action})`)
  say()
  say(`- Run-time: ${runtime.length === 0 ? 'none' : runtime.join(', ')}`)
  say(`- Peers: ${peers.length === 0 ? 'none' : peers.join(', ')}`)
  say(
    `- Workspace: ${workspace.length === 0 ? 'none' : workspace.map((n) => `\`${n}\`${WANTED.some(([w]) => w === n) ? '' : ' (not in the table)'}`).join(', ')}`,
  )
  say(
    `- Framework: ${framework === undefined ? 'does not use `acrylblends`' : `declares \`acrylblends\` ${framework} (${manifest.dependencies?.acrylblends ? 'a dependency: make it a peer' : 'already a peer'})`}`,
  )
  say(
    `- DSH client: ${client === undefined ? 'no client bundle' : `platform ${client.platform ?? 'web'}, inject ${(client.inject ?? []).map((n) => `\`${n}\``).join(', ') || 'none'}`}`,
  )
  say(
    `- DSH packages imported by its source: ${dshImports.length === 0 ? 'none' : dshImports.map((n) => `\`${n}\``).join(', ')}`,
  )
  say(
    `- Ships: ${(manifest.files ?? []).join(', ') || '(no files list)'}; bundle patch: ${manifest.dsh?.bundle?.patch ?? 'none'}`,
  )
  say(
    `- Tests to port: ${tests.length} files, ${lines(tests)} lines (${manifest.scripts?.test ?? 'no test script'})`,
  )
  say()
}
say('## The peer-dependency fix, scoped')
say()
const toPeer = details
  .filter(
    ([, action, manifest]) => action === 'port' && manifest.dependencies?.acrylblends !== undefined,
  )
  .map(([name]) => `\`${name}\``)
say(
  `Ported packages that declare \`acrylblends\` as a dependency and must declare it as a peer: ${toPeer.length === 0 ? 'none' : toPeer.join(', ')}. The rest either do not use the framework or already have it as a peer.`,
)
const outside = [
  ...new Set(
    details.flatMap(([, action, manifest]) =>
      action === 'port'
        ? Object.entries({ ...manifest.dependencies, ...manifest.peerDependencies })
            .filter(([, r]) => String(r).startsWith('workspace:'))
            .map(([n]) => n)
        : [],
    ),
  ),
].filter((n) => !WANTED.some(([w]) => w === n))
say()
say(
  `Workspace dependencies of ported packages that are not rows of the table (to bring or replace): ${outside.length === 0 ? 'none' : outside.map((n) => `\`${n}\``).join(', ')}.`,
)
console.log(out.join('\n'))
