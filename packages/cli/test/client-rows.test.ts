/** The launcher's client rows on upgrade: missing rows are added, and every row the app already has survives as it is. */
import { describe, expect, it } from 'vitest'
import { mergeHostClientRows, parseHostClientRows } from '../src/ide-profile.ts'

const row = (id: string, name: string, config?: unknown) => ({
  id,
  name,
  ...(config === undefined ? {} : { config }),
})
const current = [
  row('client-modules', '@deepseek-ai/dsh-client-modules'),
  row('ui-attachment', '@deepseek-ai/dsh-client-ui-attachment'),
]
const host = (rows: unknown[]) =>
  `// Generated by acrylblends: launcher\nconst clientRows = ${JSON.stringify(rows, null, 2)}\nconst hostLayer = []\n`

describe('the host script client rows', () => {
  it('adds the rows the app lacks and keeps the rows it has, including a config a person changed', () => {
    const app = host([
      row('client-modules', '@deepseek-ai/dsh-client-modules', { keep: true }),
      row('my-own', './my-own.mjs'),
    ])
    const merged = mergeHostClientRows(host(current), app)
    expect(merged.added).toEqual(['@deepseek-ai/dsh-client-ui-attachment'])
    expect(parseHostClientRows(merged.text)).toEqual([
      row('client-modules', '@deepseek-ai/dsh-client-modules', { keep: true }),
      row('my-own', './my-own.mjs'),
      row('ui-attachment', '@deepseek-ai/dsh-client-ui-attachment'),
    ])
    // The rest of the launcher is the current one.
    expect(merged.text).toContain('const hostLayer = []')
  })

  it('is idempotent once the rows are there', () => {
    const once = mergeHostClientRows(host(current), host([row('my-own', './my-own.mjs')]))
    const twice = mergeHostClientRows(host(current), once.text)
    expect(twice.text).toBe(once.text)
    expect(twice.added).toEqual([])
  })

  it('leaves a new app and an unreadable array alone', () => {
    expect(mergeHostClientRows(host(current), undefined)).toEqual({
      text: host(current),
      added: [],
    })
    expect(mergeHostClientRows(host(current), 'no array here')).toEqual({
      text: host(current),
      added: [],
    })
  })
})
