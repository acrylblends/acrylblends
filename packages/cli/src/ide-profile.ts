/**
 * `scripts/ide-host.mjs`: the app's launcher. It boots the framework's node server and the webServer port the driver rows register on, then the frame
 * layer, and mounts DSH's driver rows from the base and web bundles (only the ids in `DRIVER_ROWS`) as ordinary rows of this composition. `--check`
 * audits the composition (every row active) and disposes it, for the gate.
 */
function hostScriptOf(profile: string): string {
  return [
    "// Generated by acrylblends: boots this app inside the ACRYL frame on the app's own node server. Regenerate instead of editing.",
    "import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'",
    "import { createRequire } from 'node:module'",
    "import { dirname, join } from 'node:path'",
    "import { fileURLToPath, pathToFileURL } from 'node:url'",
    "import { DEFAULT_SCHEMA, dump as dumpYaml, Type, load as parseYaml } from 'js-yaml'",
    '',
    "const appRoot = join(dirname(fileURLToPath(import.meta.url)), '..')",
    "const profileName = '" + profile + "'",
    "const home = process.env.ACRYLBLENDS_HOME ?? join(appRoot, '.acrylblends')",
    "// DSH's rows keep their files in this app's own home: set before any driver row is imported.",
    'process.env.DSH_HOME = home',
    '// Before any DSH module is imported: its home resolution reads the environment at import time.',
    "const { boot } = await import('@deepseek-ai/dsh-app-boot')",
    "const port = process.env.ACRYLBLENDS_PORT ?? '0'",
    "const check = process.argv.includes('--check')",
    'const require = createRequire(import.meta.url)',
    '/** The `!!js` tag the loader evaluates: js-yaml needs the same type the Cordis include plugin declares. */',
    "const JsExpr = new Type('tag:yaml.org,2002:js', {",
    "  kind: 'scalar',",
    '  construct: (data) => ({ __jsExpr: data }),',
    '  represent: (data) => data.__jsExpr,',
    '})',
    'const load = (text) => parseYaml(text, { schema: DEFAULT_SCHEMA.extend([JsExpr]) })',
    '',
    '/** The driver rows above are selected from the bundles by id; nothing else of DSH is mounted. */',
    'const DRIVER_ROWS = ' + JSON.stringify(DRIVER_ROWS, null, 2).replaceAll('\n', '\n'),
    '',
    "/** A bundle's patch files, in application order, as the package declares them. */",
    'function bundlePatches(packageName) {',
    "  const dir = dirname(require.resolve(packageName + '/package.json'))",
    "  const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))",
    '  const files = manifest.dsh?.bundle?.patch',
    "  const list = typeof files === 'string' ? [files] : Array.isArray(files) ? files : []",
    "  return list.flatMap((file) => load(readFileSync(join(dir, file), 'utf8')) ?? [])",
    '}',
    '',
    '/** Keep only the driver rows: insert lists filtered entry by entry, id-targeted patches only when they hit a driver row. */',
    'function onlyDriverRows(patches) {',
    '  const kept = []',
    '  for (const patch of patches) {',
    '    if (Array.isArray(patch.insert)) {',
    '      const insert = patch.insert.filter((entry) => DRIVER_ROWS.includes(entry.id))',
    '      if (insert.length > 0) kept.push({ ...patch, insert })',
    "    } else if (typeof patch.id === 'string' && DRIVER_ROWS.includes(patch.id)) kept.push(patch)",
    '  }',
    '  return kept',
    '}',
    '',
    "const frameLayer = load(readFileSync(join(appRoot, 'cordis.patch.yml'), 'utf8')) ?? []",
    "/** Our host rows first: the framework's node server, then the webServer port the driver rows register on (they are the app's, not DSH's). */",
    'const clientRows = ' + JSON.stringify(CLIENT_ROWS, null, 2).replaceAll('\\n', '\\n'),
    'const hostLayer = [{',
    '  insert: [',
    "    { id: 'node-server', name: './plugins/acryl-node-server/src/index.ts', config: { hostname: '127.0.0.1', port: Number(port), scan: Number(port) === 0 ? 0 : 20 } },",
    "    { id: 'web-server', name: './plugins/acryl-web-server/src/index.ts' },",
    "    { id: 'page', name: './plugins/acryl-page/src/index.ts' },",
    '    ...clientRows,',
    '  ],',
    '}]',
    "// The composition: the driver rows selected from the bundles, the host rows and the app's frame layer, in the order they mount.",
    'const composition = [',
    "  ...onlyDriverRows(bundlePatches('@deepseek-ai/dsh-base')),",
    "  ...onlyDriverRows(bundlePatches('@deepseek-ai/dsh-web-app')),",
    '  ...hostLayer,',
    '  ...frameLayer,',
    ']',
    '',
    "// The app's DSH profile, which DSH's Settings, config editor and plugin manager read and write (docs/plans/ide-host-inversion.md, section 20):",
    '// - package.json: the profile manifest (no DSH bundles; the composition is ours), created once when the app has none.',
    '// - cordis.patch.yml: the composition, regenerated on every boot from the layers above, so an upgrade or a framework bump never leaves a stale copy.',
    '// - settings.patch.yml: the profile patch document ProfileContext.patchPath points at. Only the config editor writes it; the host creates it empty',
    '//   when missing and never rewrites it, so the Settings edits of the app survive a boot, an upgrade and a framework bump.',
    'mkdirSync(home, { recursive: true })',
    "const manifestPath = join(home, 'package.json')",
    '// The composition is a profile bundle: bundle layers are applied before the profile patch document, so a Settings edit always wins over a row the',
    '// composition also configures. DSH resolves it from the profile directory like any installed bundle, and the launcher rewrites it on every boot.',
    "const bundleDir = join(home, 'node_modules', 'acrylblends-frame')",
    'mkdirSync(bundleDir, { recursive: true })',
    "writeFileSync(join(bundleDir, 'package.json'), `${JSON.stringify({ name: 'acrylblends-frame', version: '0.0.0', private: true, dsh: { bundle: { patch: 'cordis.patch.yml' } } }, null, 2)}\\n`)",
    'const compositionHeader =',
    '  "# Generated by acrylblends: the host composition of this app, a profile bundle. Rewritten on every boot from the launcher layers; do not edit. Settings live in settings.patch.yml.\\n"',
    "writeFileSync(join(bundleDir, 'cordis.patch.yml'), compositionHeader + dumpYaml(composition, { schema: DEFAULT_SCHEMA.extend([JsExpr]), noRefs: true }))",
    "writeFileSync(manifestPath, `${JSON.stringify({ name: profileName, private: true, dependencies: { 'acrylblends-frame': '0.0.0' }, dsh: { profile: { bundles: ['acrylblends-frame'] } } }, null, 2)}\\n`)",
    "const settingsPath = join(home, 'settings.patch.yml')",
    "if (!existsSync(settingsPath)) writeFileSync(settingsPath, '[]\\n')",
    '',
    '// Boot reads the same list readProfilePatches will: the composition bundle first, then the settings document, which is also the order DSH uses for',
    '// bundles and the profile patch, so the first reconcile is a no-op recomposition and every later one differs only by the edited patch.',
    "const compositionLayer = load(readFileSync(join(bundleDir, 'cordis.patch.yml'), 'utf8')) ?? []",
    "const settingsLayer = load(readFileSync(settingsPath, 'utf8')) ?? []",
    "/** The profile context DSH's settings row, config editor and plugin manager read. */",
    'const profileContext = {',
    "  name: 'web',",
    '  dir: home,',
    '  patchPath: settingsPath,',
    "  installAnchor: join(appRoot, 'package.json'),",
    '  cwd: appRoot,',
    '  home,',
    '  startedBundles: [],',
    '  overlays: [],',
    '  telemetryDisabledEnv: process.env.DSH_TELEMETRY_DISABLED,',
    '}',
    'const layers = [compositionLayer, settingsLayer]',
    'let ctx',
    'try {',
    "  ctx = await boot('" +
      profile +
      "', join(appRoot, 'cordis.yml'), layers.flat(), (hostContext) => {",
    "    hostContext.provide('profileContext', profileContext)",
    "  }, pathToFileURL(join(appRoot, 'package.json')).href)",
    '} catch (error) {',
    "  // A row that fails before it has a plugin (a module that is not one, an import that throws) is reported as 'failed to import' with no cause; the boot's",
    '  // StartupError carries the original failures. Print each one, by row id and module, then fail: a silent half-composed host is never an option.',
    '  const entries = Array.isArray(error?.entries) ? error.entries : []',
    '  const failures = entries.filter(({ outcome }) => outcome?.kind === "failed")',
    '  console.error(`acrylblends host: startup failed (${String(failures.length)} row(s))`)',
    '  for (const { entry, outcome } of failures) {',
    '    const cause = outcome.error',
    '    const detail = cause instanceof Error ? cause.stack ?? cause.message : String(cause)',
    '    console.error(`- ${entry.id} (${entry.options?.name ?? "?"}): ${detail}`)',
    '  }',
    '  const cause = error?.cause',
    '  if (failures.length === 0 && cause !== undefined) console.error(cause instanceof Error ? cause.stack ?? cause.message : String(cause))',
    '  process.exit(1)',
    '}',
    "const server = ctx.get('nodeServer')",
    "const connection = ctx.get('connection')",
    "// The chat's remote RPC is token-authenticated: the printed URL carries the launch token, and the page exchange turns it into a cookie.",
    'const url = server === undefined ? undefined : connection === undefined ? server.url : connection.authenticatedUrl(server.url)',
    "console.log(`acrylblends host: ${url ?? 'no node server'}`)",
    'if (check) {',
    "  const loader = ctx.get('loader')",
    '  const rows = [...loader.entries()]',
    '  const stalled = []',
    '  for (const row of rows) {',
    '    const state = row.fiber?.state',
    '    if (row.disabled) continue',
    "    if (state !== 2 && state !== 4) stalled.push(`${row.id} (${row.options.name}): ${state === undefined ? 'no fiber' : String(state)}`)",
    '  }',
    '  const webRows = rows.filter((row) => /(^|\\/)(host-webserver|web-app|web-frontend)$/u.test(row.options.name))',
    '  if (stalled.length > 0 || webRows.length > 0) {',
    "    console.error('acrylblends host: composition check failed')",
    '    for (const line of stalled) console.error(`- not active: ${line}`)',
    '    for (const row of webRows) console.error(`- a DSH web row is mounted: ${row.id} (${row.options.name})`)',
    '    process.exitCode = 1',
    '  } else {',
    '    console.log(`acrylblends host: every row active (${String(rows.length)} rows), no DSH web row mounted`)',
    '  }',
    '  // The Cordis way: a provider removed puts its consumer PENDING, restoring it activates it again; a reload adds nothing twice.',
    '  // The rows live under the include entry (the launcher mounts one config file), so an id is found by its last segment.',
    '  const findRow = (id) => rows.find((row) => row.id === id || row.id.endsWith(`:${id}`))',
    '  const stateOf = (id) => findRow(id)?.fiber?.state',
    "  await loader.update(findRow('credentials').id, { disabled: true })",
    '  await loader.await()',
    "  const pendingAfterRemoval = stateOf('connection') === 0",
    "  await loader.update(findRow('credentials').id, { disabled: false })",
    '  await loader.await()',
    "  const activeAfterRestore = stateOf('connection') === 2",
    '  for (let round = 0; round < 2; round += 1) {',
    "    await loader.update(findRow('session-title').id, { disabled: true })",
    "    await loader.update(findRow('session-title').id, { disabled: false })",
    '    await loader.await()',
    '  }',
    "  const reloaded = stateOf('session-title') === 2",
    '  if (!pendingAfterRemoval || !activeAfterRestore || !reloaded) {',
    '    console.error(`acrylblends host: lifecycle check failed (pending ${String(pendingAfterRemoval)}, restored ${String(activeAfterRestore)}, reloaded ${String(reloaded)})`)',
    '    process.exitCode = 1',
    '  } else {',
    "    console.log('acrylblends host: PENDING on provider removal, active on restore, two reloads clean')",
    '  }',
    '  await ctx.fiber.dispose()',
    '} else {',
    "  for (const signal of ['SIGINT', 'SIGTERM']) process.once(signal, () => { void ctx.fiber.dispose() })",
    '}',
    '',
  ].join('\n')
}

/** `acrylblends-<app>`, safe for a DSH profile name: lowercase, dashes, nothing else. */
export function profileNameFor(appName: string): string {
  const slug = appName
    .toLowerCase()
    .replaceAll(/[^a-z0-9]+/gu, '-')
    .replaceAll(/^-+|-+$/gu, '')
  return `acrylblends-${slug === '' ? 'app' : slug}`
}

/** A package name as a YAML scalar: a scoped name starts with `@`, which YAML reserves at the start of a scalar, so it is quoted. */
const yamlName = (name: string): string => (name.startsWith('@') ? `'${name}'` : name)

function overlayOf(
  packages: readonly IdeProfilePackage[],
  door = false,
  appRows: readonly {
    readonly id: string
    readonly name: string
    /** The Loader entry option: services this row's whole subtree provides in its own realm instead of the host's. */
    readonly isolate?: Readonly<Record<string, true>>
  }[] = [],
): string {
  const rows = packages
  const disabled = new Set(packages.flatMap((entry) => entry.disables ?? []))
  const lines = [
    '# Generated by acrylblends: the DSH overlay that mounts the ACRYL frame. Regenerate instead of editing.',
    '- insert:',
    '    - id: app-instance',
    '      name: ./app/runtime.mjs',
    ...(door ? ['    - id: acryl-door', '      name: ./plugins/acryl-door/src/index.ts'] : []),
    ...appRows.flatMap((row) => [
      `    - id: ${row.id}`,
      `      name: ${row.name}`,
      ...(row.isolate === undefined ? [] : [`      isolate: ${JSON.stringify(row.isolate)}`]),
    ]),
  ]
  for (const entry of rows) {
    lines.push(`    - id: ${entry.row ?? entry.name}`, `      name: ${yamlName(entry.name)}`)
  }
  // The chat driver's connection registers node routes on the framework's webServer port; it needs no DSH web runtime, so the row's
  // webRuntime inject and its expression are replaced by the one fact it needs here: which hosts the remote may trust.
  lines.push('- id: connection', '  inject: []', '  config:', "    trustedHosts: ['127.0.0.1']")
  // The chat's first workspace lives in the app's own data home, not the user's Documents: the workspace controller creates the
  // default workspace under this directory, so a first chat is inside the app folder (which the workspace registers as its first
  // project) and a test run never writes into a real home.
  lines.push(
    '- id: workspace-controller',
    '  config:',
    "    documentsDirectory: !!js process.env.ACRYLBLENDS_HOME ?? process.cwd() + '/.acrylblends'",
  )
  for (const id of [...disabled].sort()) {
    lines.push('- id: ' + id, '  disabled: true')
  }
  return `${lines.join('\n')}\n`
}

/**
 * The files a fresh app's profile needs, without touching the disk: the overlay text and the app's `package.json` with the DSH pin, the framework, the
 * frame packages and a `dev` script on the app's own profile. An existing `package.json` keeps its keys; only the generated fields are set.
 */
export function ideProfilePlan(input: IdeProfileInput, existing?: string): IdeProfilePlan {
  const profile = profileNameFor(input.appName)
  const packages = (input.packages ?? FRAME_PACKAGES).map((entry) => ({
    ...entry,
    spec: entry.spec === '' ? (input.spec?.(entry.row ?? entry.name) ?? '') : entry.spec,
  }))
  const dependencies: Record<string, string> = {
    // DSH rides as the chat/session driver: the two bundles it is selected from, its boot glue and the generic Cordis loader; pinned exactly.
    // One Cordis for the whole composition: DSH 0.2.0-rc.2's own rows run on 4.0.5, and the framework's plugins accept it (^4.0.2).
    '@deepseek-ai/cordis': '4.0.5',
    '@deepseek-ai/cordis-plugin-loader': '~1.0.6',
    '@deepseek-ai/dsh-app-boot': input.dshVersion,
    '@deepseek-ai/dsh-base': input.dshVersion,
    '@deepseek-ai/dsh-web-app': input.dshVersion,
    acrylblends: input.frameworkVersion,
    'js-yaml': '^4.2.0',
    ...input.dependencies,
  }
  for (const entry of packages)
    if (entry.installed !== true && entry.spec !== '') dependencies[entry.name] = entry.spec
  const manifest =
    existing === undefined
      ? { name: input.appName, private: true, type: 'module' }
      : JSON.parse(existing)
  return {
    profile,
    overlay: overlayOf(packages, input.door === true, input.rows ?? []),
    packageJson: `${JSON.stringify(mergeManifest(manifest, dependencies), null, 2)}\n`,
    rootConfig: '[]\n',
    hostScript: hostScriptOf(profile),
  }
}

/** The app's manifest with the generated fields set: dependencies merged (generated wins), the dev script on its own profile, keys in a stable order. */
function mergeManifest(
  manifest: Record<string, unknown>,
  dependencies: Record<string, string>,
): Record<string, unknown> {
  const sorted = Object.fromEntries(
    Object.entries(dependencies).sort(([a], [b]) => a.localeCompare(b)),
  )
  // `dev` boots the launcher; `start` stays the app's own server (production).
  const scripts = {
    ...(manifest.scripts as Record<string, string> | undefined),
    dev: 'node --import ./plugins/acryl-node-server/src/register.ts scripts/ide-host.mjs',
  }
  return {
    ...manifest,
    dependencies: { ...(manifest.dependencies as Record<string, string> | undefined), ...sorted },
    scripts,
  }
}

/** What `applyIdeProfile` did: the files it wrote, and the ones already right. */
export interface IdeProfileWrite {
  readonly written: readonly string[]
  readonly unchanged: readonly string[]
}

/**
 * The first line of every file this module generates. `acrylblends upgrade` uses it to tell a file it may rewrite from one the app wrote (a hand-made
 * `cordis.patch.yml` for DSH, say): a file without the marker is refused, never overwritten.
 */
export const GENERATED_MARKER = /^(?:#|\/\/) Generated by acrylblends:/u

/** The generated files, in the order this module writes them, with the plan field each one's text comes from. */
const GENERATED_FILES: readonly {
  readonly file: string
  readonly of: (plan: IdeProfilePlan) => string
}[] = [
  { file: 'cordis.patch.yml', of: (plan) => plan.overlay },
  { file: 'cordis.yml', of: (plan) => plan.rootConfig },
  { file: 'scripts/ide-host.mjs', of: (plan) => plan.hostScript },
  { file: 'app/runtime.mjs', of: () => APP_INSTANCE_ROW },
]

/** What writing the profile into an existing app would do to one generated file. `conflict`: the file exists and acrylblends did not write it. */
export interface IdeProfileFileWrite {
  readonly file: string
  readonly text: string
  readonly state: 'add' | 'same' | 'update' | 'conflict'
}

/** The write plan for an app that already exists, computed before anything is touched so a refusal leaves the folder exactly as it was. */
export interface IdeProfileWritePlan {
  readonly plan: IdeProfilePlan
  /** The generated files, with what writing would do to each. */
  readonly files: readonly IdeProfileFileWrite[]
  /** Whether `package.json` changes once merged (a merge, never a conflict: the app owns that file). */
  readonly manifestChanged: boolean
}

/** The door is app source, not a registry package: the row exists when the app carries it, and nothing fails when it does not. */
function withDoor(root: string, input: IdeProfileInput): IdeProfileInput {
  return { ...input, door: existsSync(join(root, 'plugins', 'acryl-door', 'src', 'index.ts')) }
}

/**
 * Plan writing the profile into `root`, which may already hold an app: a file this module generated (its first line carries the marker) is an `update`, a
 * file the app wrote is a `conflict` and must be refused by the caller, a missing file is an `add`. The bytes are exactly what `applyIdeProfile` writes.
 */
export function planIdeProfileWrite(root: string, input: IdeProfileInput): IdeProfileWritePlan {
  const manifestFile = join(root, 'package.json')
  const existing = existsSync(manifestFile) ? readFileSync(manifestFile, 'utf8') : undefined
  const plan = ideProfilePlan(withDoor(root, input), existing)
  const files = GENERATED_FILES.map(({ file, of }) => {
    const text = of(plan)
    const path = join(root, file)
    if (!existsSync(path)) return { file, text, state: 'add' as const }
    const before = readFileSync(path, 'utf8')
    if (before === text) return { file, text, state: 'same' as const }
    const firstLine = before.split('\n', 1)[0] ?? ''
    return {
      file,
      text,
      state: GENERATED_MARKER.test(firstLine) ? ('update' as const) : ('conflict' as const),
    }
  })
  return { plan, files, manifestChanged: existing !== plan.packageJson }
}

/** Write a plan made by {@link planIdeProfileWrite}: only the files whose bytes differ, and `package.json` only when the merge changes it. */
export function writeIdeProfilePlan(root: string, planned: IdeProfileWritePlan): IdeProfileWrite {
  const written: string[] = []
  const unchanged: string[] = []
  for (const file of planned.files) {
    if (file.state === 'same') {
      unchanged.push(file.file)
      continue
    }
    const path = join(root, file.file)
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, file.text)
    written.push(file.file)
  }
  if (planned.manifestChanged) {
    writeFileSync(join(root, 'package.json'), planned.plan.packageJson)
    written.push('package.json')
  } else unchanged.push('package.json')
  return { written, unchanged }
}

/** The frame packages' specs while the ide packages are unpublished (`ACRYLBLENDS_FRAME_PACKAGES`; see `init`). Unset or malformed: undefined. */
export interface FrameProfileSpecs {
  readonly dshVersion: string
  readonly frameworkVersion: string
  readonly packages: Readonly<Record<string, string>>
}

export function frameProfileFromEnv(): FrameProfileSpecs | undefined {
  const raw = process.env.ACRYLBLENDS_FRAME_PACKAGES
  if (raw === undefined || raw.trim() === '') return undefined
  try {
    const parsed = JSON.parse(raw) as {
      dshVersion?: unknown
      frameworkVersion?: unknown
      packages?: unknown
    }
    if (typeof parsed.dshVersion !== 'string' || typeof parsed.frameworkVersion !== 'string')
      return undefined
    const packages: Record<string, string> = {}
    for (const [key, value] of Object.entries((parsed.packages ?? {}) as Record<string, unknown>))
      if (typeof value === 'string') packages[key] = value
    return { dshVersion: parsed.dshVersion, frameworkVersion: parsed.frameworkVersion, packages }
  } catch {
    return undefined
  }
}

/**
 * The specs for an app that may or may not be framed already: the environment variable first (a pre-frame app has no pins of its own), then the app's own
 * `package.json` (a framed app carries the DSH pin, the framework and the frame packages, so an upgrade regenerates from what that app installed).
 * Undefined when neither says: the caller then leaves the app on the framework alone and says why.
 */
export function frameProfileForApp(root: string): FrameProfileSpecs | undefined {
  const fromEnv = frameProfileFromEnv()
  if (fromEnv !== undefined) return fromEnv
  const manifestFile = join(root, 'package.json')
  if (!existsSync(manifestFile)) return undefined
  let manifest: { dependencies?: Record<string, unknown> }
  try {
    manifest = JSON.parse(readFileSync(manifestFile, 'utf8')) as typeof manifest
  } catch {
    return undefined
  }
  const dependencies = manifest.dependencies ?? {}
  const dshVersion = dependencies['@deepseek-ai/dsh-base']
  const frameworkVersion = dependencies.acrylblends
  if (typeof dshVersion !== 'string' || typeof frameworkVersion !== 'string') return undefined
  const packages: Record<string, string> = {}
  for (const entry of FRAME_PACKAGES)
    if (typeof dependencies[entry.name] === 'string')
      packages[entry.name] = dependencies[entry.name] as string
  if (Object.keys(packages).length === 0) return undefined
  return { dshVersion, frameworkVersion, packages }
}

/**
 * Write the profile into `root`: `cordis.patch.yml` and the app's `package.json`. Idempotent: a file whose bytes are already the generated ones is not
 * touched, so a second run reports it under `unchanged` and the git working tree stays clean.
 */
export function applyIdeProfile(root: string, input: IdeProfileInput): IdeProfileWrite {
  mkdirSync(root, { recursive: true })
  return writeIdeProfilePlan(root, planIdeProfileWrite(root, input))
}
