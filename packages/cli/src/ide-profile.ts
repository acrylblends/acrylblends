/**
 * The DSH profile an app runs on: one named profile per app, and the overlay that mounts the ACRYL frame over DSH's web profile.
 *
 * Slice 1 of the IDE port (`docs/plans/ide-port.md`): DSH hosts the application, so an app's server is `dsh --profile acrylblends-<app> --patch
 * cordis.patch.yml`. The overlay is committed beside the app (its rows resolve from the folder that holds it, which sees the app's `node_modules`), and the
 * app's `package.json` carries the DSH pin and the frame packages. Generation is deterministic and idempotent: asking twice writes the same bytes and the
 * second call reports nothing changed, so a template or an upgrade can call it freely.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

/** One package the frame mounts, with the spec the app installs it by (a range, or `file:` for a local checkout). */
export interface IdeProfilePackage {
  /** The package name as the overlay's row `name:` writes it. */
  readonly name: string
  /** What the app's `package.json` asks for. */
  readonly spec: string
  /** The Loader row id; defaults to the package name (the row-id rule). */
  readonly row?: string
  /** Leave this DSH row out of the composition (its functionality comes from the frame). */
  readonly disables?: readonly string[]
  /** A row of a package the app already installs (the framework's own subpaths): in the overlay, not in `dependencies`. */
  readonly installed?: boolean
}

/** Where an app keeps its data, for the plugins that inject `appInstance` (the framework's settings service does): the slice 0 row, kept in the app. */
export const APP_INSTANCE_ROW = `// Generated by acrylblends: the app's own folder family, for the plugins that inject appInstance.
import { join } from 'node:path'

export const name = 'app-instance'

export function apply(ctx) {
  ctx.effect(() => {
    const instance = ctx.reflect.provide('appInstance', {
      root: process.cwd(),
      home: process.env.ACRYLBLENDS_HOME ?? join(process.cwd(), '.acrylblends'),
    })
    return () => {
      void instance()
    }
  }, 'app-instance')
}
`

/** The packages the frame mounts, in row order: the router pair, the host services, the frame's client plugins. */
export const FRAME_PACKAGES: readonly IdeProfilePackage[] = [
  { name: 'acrylblends/cordis/router', spec: '', row: 'acryl-router', installed: true },
  { name: 'acrylblends/cordis/router-http', spec: '', row: 'acryl-router-http', installed: true },
  { name: 'acryl-web', spec: '' },
  { name: 'acryl-settings', spec: '' },
  { name: 'acryl-shortcuts', spec: '' },
  { name: 'acryl-app-shell', spec: '' },
  { name: 'acryl-workspace', spec: '' },
  {
    name: 'dsh-client-ui-brand-acryl',
    spec: '',
    row: 'ui-brand-acryl',
    disables: ['ui-brand-official'],
  },
]

export interface IdeProfileInput {
  /** The app's name: its folder name, and the profile's suffix. */
  readonly appName: string
  /** `@deepseek-ai/dsh` exactly, never a range: DSH's APIs are pre-stable and a bump is a decision. */
  readonly dshVersion: string
  /** The framework's range or exact version. */
  readonly frameworkVersion: string
  /** What the frame mounts. Defaults to {@link FRAME_PACKAGES} with `spec` filled from `versions` or `file:`. */
  readonly packages?: readonly IdeProfilePackage[]
  /** Spec for one of the default packages, when it is not published yet. */
  readonly spec?: (name: string) => string | undefined
  /** Further packages the app installs (an unpublished frame package's own dependencies, in a checkout). */
  readonly dependencies?: Readonly<Record<string, string>>
  /** Whether the app carries the door at `plugins/acryl-door/src/index.ts`: a row then mounts it, and an app without one simply has no door. */
  readonly door?: boolean
}

/** What generation writes, as text, so the same plan can be compared before writing. */
export interface IdeProfilePlan {
  /** The DSH profile's name: one per app, so two apps never share one. */
  readonly profile: string
  /** The overlay, as committed `cordis.patch.yml`. */
  readonly overlay: string
  /** The app's `package.json`, merged with what the profile needs. */
  readonly packageJson: string
  /** `scripts/ide-profile.mjs`: creates the app's profile from the app's own installed packages, with absolute paths (DSH installs them into the profile). */
  readonly profileScript: string
}

/**
 * The script that creates the app's profile: it stages the frame's packages and every workspace dependency they reach (a `file:` dependency keeps its
 * `workspace:*` ranges, which pnpm inside the profile cannot resolve, so each becomes a copy with those ranges pointing at the other staged copies), then
 * installs DSH's web app, the framework and the staged copies into the app's own profile.
 */
function profileScriptOf(
  profile: string,
  packages: readonly IdeProfilePackage[],
  dshVersion: string,
  frameworkVersion: string,
): string {
  const names = packages
    .filter((entry) => entry.installed !== true && entry.spec !== '')
    .map((entry) => entry.name)
  return [
    "// Generated by acrylblends: creates this app's DSH profile (" +
      profile +
      ") from the app's own installed packages. Regenerate instead of editing.",
    "import { spawnSync } from 'node:child_process'",
    "import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'",
    "import { join } from 'node:path'",
    '',
    'const wanted = ' + JSON.stringify(names),
    "const modules = join(process.cwd(), 'node_modules')",
    "const stage = join(process.cwd(), '.acrylblends-ide')",
    "const safe = (name) => name.replace('/', '__').replace('@', '')",
    'const order = []',
    'const seen = new Set()',
    "const manifestOf = (name) => JSON.parse(readFileSync(join(modules, name, 'package.json'), 'utf8'))",
    'const need = (name) => {',
    "  if (seen.has(name) || !existsSync(join(modules, name, 'package.json'))) return",
    '  seen.add(name)',
    '  const manifest = manifestOf(name)',
    "  for (const field of ['dependencies', 'peerDependencies'])",
    '    for (const [dependency, range] of Object.entries(manifest[field] ?? {}))',
    "      if (String(range).startsWith('workspace:')) need(dependency)",
    '  order.push(name)',
    '}',
    'for (const name of wanted) need(name)',
    'rmSync(stage, { recursive: true, force: true })',
    'for (const name of order) {',
    '  const from = join(modules, name)',
    '  const to = join(stage, safe(name))',
    '  mkdirSync(to, { recursive: true })',
    '  const manifest = manifestOf(name)',
    "  for (const entry of manifest.files ?? ['lib']) {",
    "    const item = entry.replace('/**', '')",
    "    if (item === 'package.json') continue",
    '    if (!existsSync(join(from, item))) continue',
    '    cpSync(join(from, item), join(to, item), { recursive: true })',
    '  }',
    "  for (const field of ['dependencies', 'peerDependencies'])",
    '    for (const [dependency, range] of Object.entries(manifest[field] ?? {}))',
    "      if (String(range).startsWith('workspace:')) manifest[field][dependency] = 'file:../' + safe(dependency)",
    "  writeFileSync(join(to, 'package.json'), JSON.stringify(manifest, null, 2) + '\\n')",
    '}',
    '',
    'const specs = [',
    "  '@deepseek-ai/dsh-web-app@" + dshVersion + "',",
    "  'acrylblends@" + frameworkVersion + "',",
    "  ...wanted.map((name) => 'file:' + join(stage, safe(name))),",
    ']',
    '// Only the frame packages are added as DSH plugins (their bundle patch becomes a row). A workspace library they depend on is installed as their',
    '// dependency from the staged copies, not added as a plugin: adding it would make DSH load a module that has no plugin to apply.',
    "// The profile's own pnpm needs its build allow-list before it installs anything (DSH's dependencies build native bindings).",
    "const dshHome = process.env.DSH_HOME ?? join(process.cwd(), '.dsh')",
    "const profileDir = join(dshHome, 'profiles', " + JSON.stringify(profile) + ')',
    'mkdirSync(profileDir, { recursive: true })',
    "writeFileSync(join(profileDir, 'pnpm-workspace.yaml'), 'allowBuilds:\\n  koffi: true\\n  node-pty: true\\n')",
    '',
    "const dsh = join(modules, '@deepseek-ai', 'dsh', 'lib', 'bin.js')",
    "const result = spawnSync(process.execPath, [dsh, 'plugin', '--profile', " +
      JSON.stringify(profile) +
      ", 'add', ...specs], { stdio: 'inherit' })",
    'process.exit(result.status ?? 1)',
    '',
  ].join('\n')
}

/** `acrylblends-<app>`, safe for a DSH profile name: lowercase, dashes, nothing else. */
export function profileNameFor(appName: string): string {
  const slug = appName
    .toLowerCase()
    .replaceAll(/[^a-z0-9]+/gu, '-')
    .replaceAll(/^-+|-+$/gu, '')
  return `acrylblends-${slug === '' ? 'app' : slug}`
}

function overlayOf(packages: readonly IdeProfilePackage[], door = false): string {
  const rows = packages
  const disabled = new Set(packages.flatMap((entry) => entry.disables ?? []))
  const lines = [
    '# Generated by acrylblends: the DSH overlay that mounts the ACRYL frame. Regenerate instead of editing.',
    '- insert:',
    '    - id: app-instance',
    '      name: ./app/runtime.mjs',
    ...(door ? ['    - id: acryl-door', '      name: ./plugins/acryl-door/src/index.ts'] : []),
  ]
  for (const entry of rows) {
    lines.push(`    - id: ${entry.row ?? entry.name}`, `      name: ${entry.name}`)
  }
  // ACRYL's frame owns the first run: DSH's API-key dialog must not cover it. `ui-settings-models` carries the switch (DSH's own onboarding config).
  lines.push('- id: ui-settings-models', '  config:', '    credentialOnboarding: false')
  for (const id of [...disabled].sort()) {
    lines.push('- id: ' + id, '  disabled: true')
  }
  return `${lines.join('\n')}\n`
}

/**
 * The files a fresh app's profile needs, without touching the disk: the overlay text and the app's `package.json` with the DSH pin, the framework, the
 * frame packages and a `dev` script on the app's own profile. An existing `package.json` keeps its keys; only the generated fields are set.
 */
export function ideProfilePlan(input: IdeProfileInput, existing?: string): IdeProfilePlan {
  const profile = profileNameFor(input.appName)
  const packages = (input.packages ?? FRAME_PACKAGES).map((entry) => ({
    ...entry,
    spec: entry.spec === '' ? (input.spec?.(entry.row ?? entry.name) ?? '') : entry.spec,
  }))
  const dependencies: Record<string, string> = {
    '@deepseek-ai/dsh': input.dshVersion,
    acrylblends: input.frameworkVersion,
    ...input.dependencies,
  }
  for (const entry of packages)
    if (entry.installed !== true && entry.spec !== '') dependencies[entry.name] = entry.spec
  const manifest =
    existing === undefined
      ? { name: input.appName, private: true, type: 'module' }
      : JSON.parse(existing)
  return {
    profile,
    overlay: overlayOf(packages, input.door === true),
    packageJson: `${JSON.stringify(mergeManifest(manifest, dependencies, profile), null, 2)}\n`,
    profileScript: profileScriptOf(profile, packages, input.dshVersion, input.frameworkVersion),
  }
}

/** The app's manifest with the generated fields set: dependencies merged (generated wins), the dev script on its own profile, keys in a stable order. */
function mergeManifest(
  manifest: Record<string, unknown>,
  dependencies: Record<string, string>,
  profile: string,
): Record<string, unknown> {
  const sorted = Object.fromEntries(
    Object.entries(dependencies).sort(([a], [b]) => a.localeCompare(b)),
  )
  // DSH needs the profile to exist before `--patch` composes it: `profile` creates it with the framework, and the overlay's rows then resolve from the app
  // folder that holds it (DSH resolves a row's bare import from the overlay's own location, which sees the app's node_modules), so the frame packages need
  // no profile entry of their own.
  const scripts = {
    ...(manifest.scripts as Record<string, string> | undefined),
    profile: 'node scripts/ide-profile.mjs',
    dev: `dsh --profile ${profile} --patch cordis.patch.yml --no-open`,
  }
  return {
    ...manifest,
    dependencies: { ...(manifest.dependencies as Record<string, string> | undefined), ...sorted },
    scripts,
  }
}

/** What `applyIdeProfile` did: the files it wrote, and the ones already right. */
export interface IdeProfileWrite {
  readonly written: readonly string[]
  readonly unchanged: readonly string[]
}

/**
 * Write the profile into `root`: `cordis.patch.yml` and the app's `package.json`. Idempotent: a file whose bytes are already the generated ones is not
 * touched, so a second run reports it under `unchanged` and the git working tree stays clean.
 */
export function applyIdeProfile(root: string, input: IdeProfileInput): IdeProfileWrite {
  mkdirSync(root, { recursive: true })
  // The door is app source, not a registry package: the row exists when the app carries it, and nothing fails when it does not.
  input = { ...input, door: existsSync(join(root, 'plugins', 'acryl-door', 'src', 'index.ts')) }
  const manifestFile = join(root, 'package.json')
  const existing = existsSync(manifestFile) ? readFileSync(manifestFile, 'utf8') : undefined
  const plan = ideProfilePlan(input, existing)
  const written: string[] = []
  const unchanged: string[] = []
  for (const [file, text] of [
    ['cordis.patch.yml', plan.overlay],
    ['package.json', plan.packageJson],
    ['scripts/ide-profile.mjs', plan.profileScript],
    ['app/runtime.mjs', APP_INSTANCE_ROW],
  ] as const) {
    const path = join(root, file)
    mkdirSync(dirname(path), { recursive: true })
    if (existsSync(path) && readFileSync(path, 'utf8') === text) unchanged.push(file)
    else {
      writeFileSync(path, text)
      written.push(file)
    }
  }
  return { written, unchanged }
}
