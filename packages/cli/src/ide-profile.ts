/** The row that roots the page (the Blends frame) and the module it is installed as: its source name in a checkout, its published name from npm. */
export const BLENDS_FRAME_ROW = 'acryl-blends-frame'

function frameModuleOf(packages: readonly IdeProfilePackage[]): string {
  return (
    packages.find((entry) => (entry.row ?? entry.name) === BLENDS_FRAME_ROW)?.name ??
    BLENDS_FRAME_ROW
  )
}

/** `acrylblends-<app>`, safe for a DSH profile name: lowercase, dashes, nothing else. */
export function profileNameFor(appName: string): string {
  const slug = appName
    .toLowerCase()
    .replaceAll(/[^a-z0-9]+/gu, '-')
    .replaceAll(/^-+|-+$/gu, '')
  return `acrylblends-${slug === '' ? 'app' : slug}`
}

/** A package name as a YAML scalar: a scoped name starts with `@`, which YAML reserves at the start of a scalar, so it is quoted. */
const yamlName = (name: string): string => (name.startsWith('@') ? `'${name}'` : name)

function overlayOf(
  packages: readonly IdeProfilePackage[],
  door = false,
  appRows: readonly {
    readonly id: string
    readonly name: string
    /** The Loader entry option: services this row's whole subtree provides in its own realm instead of the host's. */
    readonly isolate?: Readonly<Record<string, true>>
  }[] = [],
): string {
  const rows = packages
  const disabled = new Set(packages.flatMap((entry) => entry.disables ?? []))
  const lines = [
    '# Generated by acrylblends: the DSH overlay that mounts the ACRYL frame. Regenerate instead of editing.',
    '- insert:',
    '    - id: app-instance',
    '      name: ./app/runtime.mjs',
    // The frame's index is not the app: the door drives the app's page in the canvas, never the frame around it (an agent's navigate would leave the frame).
    // The canvas prefix goes with it: `act navigate --path /board` reaches the app's /board at the canvas prefix, the same path it has on its own server.
    ...(door
      ? [
          '    - id: acryl-door',
          '      name: ./plugins/acryl-door/src/index.ts',
          '      config:',
          '        hostIndex: false',
          `        appBase: ${FRAME_PAGE_PREFIX}`,
        ]
      : []),
    ...appRows.flatMap((row) => [
      `    - id: ${row.id}`,
      `      name: ${row.name}`,
      ...(row.isolate === undefined ? [] : [`      isolate: ${JSON.stringify(row.isolate)}`]),
    ]),
  ]
  for (const entry of rows) {
    lines.push(`    - id: ${entry.row ?? entry.name}`, `      name: ${yamlName(entry.name)}`)
    // The app's page, which the frame shows in its centre.
    if ((entry.row ?? entry.name) === BLENDS_FRAME_ROW)
      lines.push('      config:', `        appPage: ${FRAME_PAGE_PREFIX}`)
    // The app is mounted under the canvas prefix, and a person (or a link) writes its root as `/app/` as often as `/app`: the frame's router reads a
    // trailing slash as the same path, so both answer the app's root and a relative link on it stays in the app.
    if ((entry.row ?? entry.name) === 'acryl-router')
      lines.push('      config:', '        trailingSlash: ignore')
  }
  // The chat driver's connection registers node routes on the framework's webServer port; it needs no DSH web runtime, so the row's
  // webRuntime inject and its expression are replaced by the one fact it needs here: which hosts the remote may trust.
  lines.push('- id: connection', '  inject: []', '  config:', "    trustedHosts: ['127.0.0.1']")
  // The chat's first workspace lives in the app's own data home, not the user's Documents: the workspace controller creates the
  // default workspace under this directory, so a first chat is inside the app folder (which the workspace registers as its first
  // project) and a test run never writes into a real home.
  lines.push(
    '- id: workspace-controller',
    '  config:',
    '    documentsDirectory: !!js process.env.DSH_HOME',
  )
  for (const id of [...disabled].sort()) {
    lines.push(`- id: ${id}`, '  disabled: true')
  }
  return `${lines.join('\n')}\n`
}

/**
 * The files a fresh app's profile needs, without touching the disk: the overlay text and the app's `package.json` with the DSH pin, the framework, the
 * frame packages and a `dev` script on the app's own profile. An existing `package.json` keeps its keys; only the generated fields are set.
 */
export function ideProfilePlan(input: IdeProfileInput, existing?: string): IdeProfilePlan {
  const profile = profileNameFor(input.appName)
  const packages = (input.packages ?? FRAME_PACKAGES).map((entry) => ({
    ...entry,
    spec: entry.spec === '' ? (input.spec?.(entry.row ?? entry.name) ?? '') : entry.spec,
  }))
  const dependencies: Record<string, string> = {
    // DSH rides as the chat/session driver: the two bundles it is selected from, its boot glue and the generic Cordis loader; pinned exactly.
    // One Cordis for the whole composition: DSH 0.2.0-rc.2's own rows run on 4.0.5, and the framework's plugins accept it (^4.0.2).
    '@deepseek-ai/cordis': '4.0.5',
    '@deepseek-ai/cordis-plugin-loader': '~1.0.6',
    '@deepseek-ai/dsh-app-boot': input.dshVersion,
    '@deepseek-ai/dsh-base': input.dshVersion,
    '@deepseek-ai/dsh-web-app': input.dshVersion,
    acrylblends: input.frameworkVersion,
    'js-yaml': '^4.2.0',
    ...input.dependencies,
  }
  for (const entry of packages)
    if (entry.installed !== true && entry.spec !== '') dependencies[entry.name] = entry.spec
  const manifest =
    existing === undefined
      ? { name: input.appName, private: true, type: 'module' }
      : JSON.parse(existing)
  return {
    profile,
    overlay: overlayOf(packages, input.door === true, input.rows ?? []),
    packageJson: `${JSON.stringify(mergeManifest(manifest, dependencies), null, 2)}\n`,
    rootConfig: '[]\n',
    hostScript: hostScriptOf(profile, frameModuleOf(packages)),
  }
}

/** The app's manifest with the generated fields set: dependencies merged (generated wins), the dev script on its own profile, keys in a stable order. */
function mergeManifest(
  manifest: Record<string, unknown>,
  dependencies: Record<string, string>,
): Record<string, unknown> {
  const sorted = Object.fromEntries(
    Object.entries(dependencies).sort(([a], [b]) => a.localeCompare(b)),
  )
  // `dev` boots the launcher; `start` stays the app's own server (production).
  const scripts = {
    ...(manifest.scripts as Record<string, string> | undefined),
    dev: 'node --import ./plugins/acryl-node-server/src/register.ts scripts/ide-host.mjs',
  }
  return {
    ...manifest,
    dependencies: { ...(manifest.dependencies as Record<string, string> | undefined), ...sorted },
    scripts,
  }
}

/** What `applyIdeProfile` did: the files it wrote, and the ones already right. */
export interface IdeProfileWrite {
  readonly written: readonly string[]
  readonly unchanged: readonly string[]
}

/**
 * The first line of every file this module generates. `acrylblends upgrade` uses it to tell a file it may rewrite from one the app wrote (a hand-made
 * `cordis.patch.yml` for DSH, say): a file without the marker is refused, never overwritten.
 */
export const GENERATED_MARKER = /^(?:#|\/\/) Generated by acrylblends:/u

/** The generated files, in the order this module writes them, with the plan field each one's text comes from. */
const GENERATED_FILES: readonly {
  readonly file: string
  readonly of: (plan: IdeProfilePlan) => string
}[] = [
  { file: 'cordis.patch.yml', of: (plan) => plan.overlay },
  { file: 'cordis.yml', of: (plan) => plan.rootConfig },
  { file: 'scripts/ide-host.mjs', of: (plan) => plan.hostScript },
  { file: 'app/runtime.mjs', of: () => APP_INSTANCE_ROW },
]

/** What writing the profile into an existing app would do to one generated file. `conflict`: the file exists and acrylblends did not write it. */
export interface IdeProfileFileWrite {
  readonly file: string
  readonly text: string
  readonly state: 'add' | 'same' | 'update' | 'conflict'
}

/** The write plan for an app that already exists, computed before anything is touched so a refusal leaves the folder exactly as it was. */
export interface IdeProfileWritePlan {
  readonly plan: IdeProfilePlan
  /** The generated files, with what writing would do to each. */
  readonly files: readonly IdeProfileFileWrite[]
  /** Whether `package.json` changes once merged (a merge, never a conflict: the app owns that file). */
  readonly manifestChanged: boolean
  /** Client rows the app's host script did not name yet, which the write adds. */
  readonly clientRowsAdded: readonly string[]
}

/** The door is app source, not a registry package: the row exists when the app carries it, and nothing fails when it does not. */
function withDoor(root: string, input: IdeProfileInput): IdeProfileInput {
  return { ...input, door: existsSync(join(root, 'plugins', 'acryl-door', 'src', 'index.ts')) }
}

/**
 * Plan writing the profile into `root`, which may already hold an app: a file this module generated (its first line carries the marker) is an `update`, a
 * file the app wrote is a `conflict` and must be refused by the caller, a missing file is an `add`. The bytes are exactly what `applyIdeProfile` writes.
 */
export function planIdeProfileWrite(root: string, input: IdeProfileInput): IdeProfileWritePlan {
  const manifestFile = join(root, 'package.json')
  const existing = existsSync(manifestFile) ? readFileSync(manifestFile, 'utf8') : undefined
  const plan = ideProfilePlan(withDoor(root, input), existing)
  const hostPath = join(root, 'scripts/ide-host.mjs')
  const appHost = existsSync(hostPath) ? readFileSync(hostPath, 'utf8') : undefined
  let clientRowsAdded: readonly string[] = []
  const files = GENERATED_FILES.map(({ file, of }) => {
    let text = of(plan)
    if (file === 'scripts/ide-host.mjs') {
      // The launcher updates as a whole; its rows are a merge, so a person's own row or a row they changed survives and only missing rows are added.
      const merged = mergeHostClientRows(text, appHost)
      text = merged.text
      clientRowsAdded = merged.added
    }
    const path = join(root, file)
    if (!existsSync(path)) return { file, text, state: 'add' as const }
    const before = readFileSync(path, 'utf8')
    if (before === text) return { file, text, state: 'same' as const }
    const firstLine = before.split('\n', 1)[0] ?? ''
    return {
      file,
      text,
      state: GENERATED_MARKER.test(firstLine) ? ('update' as const) : ('conflict' as const),
    }
  })
  return { plan, files, manifestChanged: existing !== plan.packageJson, clientRowsAdded }
}

/** Write a plan made by {@link planIdeProfileWrite}: only the files whose bytes differ, and `package.json` only when the merge changes it. */
export function writeIdeProfilePlan(root: string, planned: IdeProfileWritePlan): IdeProfileWrite {
  const written: string[] = []
  const unchanged: string[] = []
  for (const file of planned.files) {
    if (file.state === 'same') {
      unchanged.push(file.file)
      continue
    }
    const path = join(root, file.file)
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, file.text)
    written.push(file.file)
  }
  if (planned.manifestChanged) {
    writeFileSync(join(root, 'package.json'), planned.plan.packageJson)
    written.push('package.json')
  } else unchanged.push('package.json')
  return { written, unchanged }
}

/**
 * Write the profile into `root`: `cordis.patch.yml` and the app's `package.json`. Idempotent: a file whose bytes are already the generated ones is not
 * touched, so a second run reports it under `unchanged` and the git working tree stays clean.
 */
export function applyIdeProfile(root: string, input: IdeProfileInput): IdeProfileWrite {
  mkdirSync(root, { recursive: true })
  return writeIdeProfilePlan(root, planIdeProfileWrite(root, input))
}
