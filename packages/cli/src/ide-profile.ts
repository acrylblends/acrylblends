export interface IdeProfileInput {
  /** The app's name: its folder name, and the profile's suffix. */
  readonly appName: string
  /** `@deepseek-ai/dsh` exactly, never a range: DSH's APIs are pre-stable and a bump is a decision. */
  readonly dshVersion: string
  /** The framework's range or exact version. */
  readonly frameworkVersion: string
  /** What the frame mounts. Defaults to {@link FRAME_PACKAGES} with `spec` filled from `versions` or `file:`. */
  readonly packages?: readonly IdeProfilePackage[]
  /** Spec for one of the default packages, when it is not published yet. */
  readonly spec?: (name: string) => string | undefined
  /** Further packages the app installs (an unpublished frame package's own dependencies, in a checkout). */
  readonly dependencies?: Readonly<Record<string, string>>
  /** The app's own rows in the overlay (the file that mounts its routes at the frame prefix), in order; none for an app without one. */
  readonly rows?: readonly {
    readonly id: string
    readonly name: string
    readonly isolate?: Readonly<Record<string, true>>
  }[]
  /** Whether the app carries the door at `plugins/acryl-door/src/index.ts`: a row then mounts it, and an app without one simply has no door. */
  readonly door?: boolean
}

/** What generation writes, as text, so the same plan can be compared before writing. */
export interface IdeProfilePlan {
  /** The host's name for this app (one per app; used in the launcher's identity and logs). */
  readonly profile: string
  /** The app's own layer, as committed `cordis.patch.yml`. */
  readonly overlay: string
  /** The app's `package.json`, merged with what the host and the driver rows need. */
  readonly packageJson: string
  /** `cordis.yml`: the empty root entry list the launcher's loader composition starts from. */
  readonly rootConfig: string
  /** `scripts/ide-host.mjs`: composes the driver rows with this app's layer and boots them on the framework's node server. */
  readonly hostScript: string
}

