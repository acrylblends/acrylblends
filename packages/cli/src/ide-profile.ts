/**
 * The host an app runs on inside the ACRYL frame: the app's own node server and loader composition, with DSH riding as the chat/session driver
 * (`docs/plans/ide-host-inversion.md`). The overlay (`cordis.patch.yml`) is the app's own layer: the frame's rows, the app's rows and the switches.
 * `scripts/ide-host.mjs` is the launcher: it composes the driver rows from DSH's base and web bundles with this app's layer and boots them on the
 * framework's node server. No DSH profile, no `dsh` launcher, no `dsh plugin add`. Generation is deterministic and idempotent: asking twice writes
 * the same bytes and the second call reports nothing changed, so a template or an upgrade can call it freely.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

/** One package the frame mounts, with the spec the app installs it by (a range, or `file:` for a local checkout). */
export interface IdeProfilePackage {
  /** The package name as the overlay's row `name:` writes it. */
  readonly name: string
  /** What the app's `package.json` asks for. */
  readonly spec: string
  /** The Loader row id; defaults to the package name (the row-id rule). */
  readonly row?: string
  /** Leave this DSH row out of the composition (its functionality comes from the frame). */
  readonly disables?: readonly string[]
  /** A row of a package the app already installs (the framework's own subpaths): in the overlay, not in `dependencies`. */
  readonly installed?: boolean
}

